-- Q7. Determine the top 3 products that generated the most revenue.

-- Solulion:
SELECT
    productLine,
    products.productName AS product_name,
    SUM(priceEach) AS total_revenue
FROM products
	LEFT JOIN orderdetails
		ON products.productCode = orderdetails.productCode
GROUP BY 
	productLine, 
    products.productName
ORDER BY SUM(priceEach) DESC
LIMIT 3;

-- Q8. Determine the total revenue for each product line.

-- Solution:
SELECT 
	products.productLine,
    products.productCode,
    SUM(orderdetails.priceEach) AS total_revenue
FROM products
	LEFT JOIN orderdetails
		ON products.productCode = orderdetails.productCode
GROUP BY 
	products.productLine,
    products.productCode
ORDER BY 
	total_revenue DESC;


-- Q9. Identify the top 5 customers based on total order value.

-- Solution:
SELECT
    orders.orderNumber,
    orders.customerNumber,
    customers.customerName,
    SUM(orderdetails.quantityOrdered) AS total_order_value
FROM
    orderdetails
        LEFT JOIN orders 
			ON orderdetails.orderNumber = orders.orderNumber
        LEFT JOIN customers 
			ON orders.customerNumber = customers.customerNumber
GROUP BY orders.orderNumber
ORDER BY orders.customerNumber DESC
LIMIT 5;


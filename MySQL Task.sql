-- Q3. Find all customers who have placed orders, including their names, order, numbers and order dates;

-- Solution:
SELECT
	customers.customerNumber AS customer_number,
	customers.customerName AS customer_name,
    orders.orderNumber,
    orders.orderDate
FROM customers
	LEFT JOIN orders
		ON customers.customerNumber = orders.customerNumber
GROUP BY
		customers.customerNumber,
		orders.orderNumber,
		orders.orderDate ;
        
        
-- Q4. Determine how many orders each customer has placed.

-- Solution:
SELECT 
	customers.customerNumber,
    customers.customerName,
    COUNT(DISTINCT orders.orderNumber) AS count_of_orders
FROM customers
	LEFT JOIN orders
		ON customers.customerNumber = orders.customerNumber
GROUP BY 
    customers.customerNumber;
    
    
-- Q5. Find orders with total value greater than $5,000. Include thecustomer name, order number, and total value.

-- Solution: 
SELECT
	customers.customerName AS customer_name,
    customers.customerNumber AS customer_number,
    orderdetails.orderNumber AS order_number,
	SUM(orderdetails.priceEach) AS total_value,
    SUM(orderdetails.quantityOrdered) AS total_quantity_ordered
FROM orderdetails
	LEFT JOIN orders
		ON orderdetails.orderNumber = orders.orderNumber
	LEFT JOIN customers
		ON orders.customerNumber = customers.customerNumber
GROUP BY 
	customers.customerName,
    customers.customerNumber,
    orderdetails.orderNumber;

-- Q6. Find orders where the shipping date is after the required date. Include order numbers and delay durations.

